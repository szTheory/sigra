defmodule ExampleWeb.Auth.SudoController do
  @moduledoc """
  Controller for sudo/re-authentication mode.

  When a user accesses a sensitive operation protected by `Sigra.Plug.RequireSudo`,
  they are redirected here to re-enter their password. On success, the session's
  `sudo_at` timestamp is updated and the user is redirected back.

  Follows GitHub's sudo pattern: redirect to `/users/sudo` with `return_to` param,
  user enters password, gets redirected back. Form submits via HTTP POST (not
  LiveView event) per D-21.

  Generated by `mix sigra.install`. Customize freely -- this module
  is owned by your application.
  """

  use ExampleWeb, :controller

  def new(conn, _params) do
    form = Phoenix.Component.to_form(%{"password" => ""}, as: "sudo")

    render(conn, :new,
      return_to: conn.params["return_to"] || ~p"/",
      form: form,
      demo_persona: demo_persona_for(conn.assigns.current_scope.user),
      demo_personas: demo_persona_options()
    )
  end

  # Dev-gated: the persona's PASSWORD only ever reaches the render assigns in a
  # dev_routes build. Mirrors session_controller.ex's demo_persona_hint gate so
  # the sudo demo Fill-password band is compiled out under mix test / prod.
  # Returns the enriched persona (`%{key, feature, …}`) for the shared demo_bar.
  if Application.compile_env(:example, :dev_routes) do
    defp demo_persona_for(user), do: Example.Demo.Personas.by_email(user.email)
  else
    defp demo_persona_for(_user), do: nil
  end

  # Dev-gated: the persona-switcher dropdown options only exist in a dev_routes
  # build. Returns `[]` under mix test / prod so the shared demo band does not
  # render at all (sudo_controller_test refutes stay green).
  if Application.compile_env(:example, :dev_routes) do
    defp demo_persona_options, do: Example.Demo.Personas.options()
  else
    defp demo_persona_options, do: []
  end

  def create(conn, %{"sudo" => %{"password" => password, "return_to" => return_to}}) do
    user = conn.assigns.current_scope.user

    case Sigra.Crypto.verify_password(password, user.hashed_password) do
      true ->
        session = conn.private[:sigra_session]
        Example.Accounts.confirm_sudo(session.hashed_token)

        # Validate return_to is a local path (not an external URL)
        safe_return_to =
          if return_to && String.starts_with?(return_to, "/") &&
               !String.starts_with?(return_to, "//") do
            return_to
          else
            ~p"/"
          end

        conn
        |> put_flash(:info, "Password confirmed.")
        |> redirect(to: safe_return_to)

      false ->
        conn
        |> put_flash(:error, "Incorrect password. Please try again.")
        |> render(:new,
          return_to: return_to,
          form: Phoenix.Component.to_form(%{"password" => ""}, as: "sudo"),
          demo_persona: demo_persona_for(conn.assigns.current_scope.user),
          demo_personas: demo_persona_options()
        )
    end
  end

  def create(conn, %{"sudo" => %{"password" => password}}) do
    create(conn, %{"sudo" => %{"password" => password, "return_to" => ~p"/"}})
  end
end
