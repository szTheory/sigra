          </p>
        </div>

        <.form
          :let={f}
          for={@form}
          action={~p"/users/sudo"}
          method="post"
          class="vt-auth__form vt-auth__form--primary"
        >
          <input type="hidden" name="sudo[return_to]" value={@return_to} />
          <.input
            field={f[:password]}
