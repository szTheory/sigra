  use ExampleWeb, :html

  def new(assigns) do
    ~H"""
    <section class="vt-auth" data-theme="system" data-testid="sudo">
      <div class="vt-auth__panel">
        <a href={~p"/"} class="vt-brand">
          <img src={~p"/images/tasklane-mark.svg"} alt="Tasklane logo" class="vt-brand__mark" />
