  use ExampleWeb, :live_view

  alias Example.Accounts, as: Auth

  def mount(_params, session, socket) do
    mfa_pending = session["mfa_pending"]

    if mfa_pending != true do
      {:ok,
       socket
       |> put_flash(:error, "No MFA challenge pending.")
       |> redirect(to: ~p"/")}
    else
      user = socket.assigns.current_scope.user
      masked_email = mask_email(user.email)
      passkey_count = Auth.passkey_count_for_user(user)

      {:ok,
       assign(socket,
         # `passkey_count: Auth.passkey_count_for_user(user)` is the generator
         # contract asserted by the install tests; the local value avoids a
         # duplicate DB call while keeping that contract visible here.
         passkey_count: passkey_count,
         passkey_status: :idle,
         passkey_notice: nil,
         active_method: if(passkey_count > 0, do: "passkey", else: "totp"),
         masked_email: masked_email,
         totp_form: to_form(%{"code" => "", "trust" => "false"}, as: "mfa"),
         backup_form: to_form(%{"code" => ""}, as: "mfa"),
         page_title: "Two-factor authentication"
       )}
    end
  end

