  LiveView for the MFA challenge page.

  Provides two-factor authentication verification with passkeys,
  TOTP authenticator codes, backup codes, auto-submit on 6 digits,
  and a trust-this-browser checkbox on the TOTP path.

  Generated by `mix sigra.install --live`. Customize freely -- this module
  is owned by your application.
