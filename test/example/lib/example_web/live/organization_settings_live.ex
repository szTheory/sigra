  Organization settings LiveView — three stacked sections on a single page
  (D-10): General (rename), Slug (change with 7-day redirect + inline sudo),
  and Danger Zone (soft-delete with inline sudo + typed-confirm of org name).

  All destructive actions use progressive disclosure (D-12): closed state
  renders a single button; clicking reveals an inline form with current
  password + typed-confirm fields. No modal dialogs, no sub-routes.

  Sudo is collected inline (D-11): the form carries a `current_password`
  field that the library's `update_slug/4` and `soft_delete_organization/4`
  functions verify via `Sigra.Crypto.verify_password/2`. On mismatch the
  library returns `{:error, :invalid_password}` and this LV surfaces the
  exact UI-SPEC copy `"That password is incorrect."` inline, without any
  redirect — form state is preserved.

  Non-owners are rejected at the plug layer by the `:org_scoped` pipeline
  with `Sigra.Plug.RequireMembership` restricted to `role: [:owner]`; this
  LV never mounts for them. Non-members receive 404 for enumeration safety
  (D-04), not 403.

  Generated by `mix sigra.install`. Customize freely — this module is
  owned by your application.
  """
