  @impl true
  def handle_event("rename", %{"organization" => params}, socket) do
    case Organizations.rename_organization(socket.assigns.current_scope, params) do
      {:ok, org} ->
        {:noreply,
         socket
         |> assign(:org, org)
         |> assign(:rename_form, to_form(%{"name" => org.name}, as: :organization))
         |> put_flash(:info, "Name updated.")}

      {:error, %Ecto.Changeset{} = changeset} ->
        {:noreply,
         socket
         |> assign(:rename_form, to_form(changeset, as: :organization))}
    end
  end

  def handle_event("open_slug_form", _params, socket) do
    {:noreply,
     socket
     |> assign(:slug_form_open?, true)
     |> assign(:slug_form, blank_slug_form())}
  end

  def handle_event("close_slug_form", _params, socket) do
    {:noreply,
     socket
     |> assign(:slug_form_open?, false)
     |> assign(:slug_form, blank_slug_form())}
  end

  def handle_event("update_slug", %{"slug_change" => params}, socket) do
    case Organizations.update_slug(socket.assigns.current_scope, params) do
      {:ok, org} ->
        {:noreply,
         socket
         |> put_flash(:info, "Slug updated. The old slug redirects for 7 days.")
         |> redirect(to: ~p"/organizations/#{org.slug}/settings")}

      {:error, :invalid_password} ->
        {:noreply,
         assign(
           socket,
           :slug_form,
           params
           |> slug_form_with_errors([{:password, "That password is incorrect."}])
         )}

      {:error, %Ecto.Changeset{} = changeset} ->
        errors = remap_slug_errors(changeset, socket.assigns.org.slug)
        {:noreply, assign(socket, :slug_form, slug_form_with_errors(params, errors))}
    end
  end

  def handle_event("open_delete_form", _params, socket) do
    {:noreply,
     socket
     |> assign(:delete_form_open?, true)
     |> assign(:delete_form, blank_delete_form())}
  end

  def handle_event("close_delete_form", _params, socket) do
    {:noreply,
     socket
     |> assign(:delete_form_open?, false)
     |> assign(:delete_form, blank_delete_form())}
  end

  def handle_event("soft_delete", %{"delete_org" => params}, socket) do
    case Organizations.soft_delete_organization(socket.assigns.current_scope, params) do
      {:ok, _org} ->
        {:noreply,
         socket
         |> put_flash(:info, "Organization deleted.")
         |> redirect(to: ~p"/organizations")}

      {:error, :invalid_password} ->
        {:noreply,
         assign(
           socket,
           :delete_form,
           delete_form_with_errors(params, [{:password, "That password is incorrect."}])
         )}

      {:error, %Ecto.Changeset{} = changeset} ->
        errors = remap_delete_errors(changeset, socket.assigns.org.name)
        {:noreply, assign(socket, :delete_form, delete_form_with_errors(params, errors))}
    end
  end

  def handle_event(
        "submit_enterprise_connection",
        %{"enterprise_connection" => params, "_action" => action},
        socket
      ) do
    scope = socket.assigns.current_scope

    result =
      case action do
        "save" -> Organizations.save_enterprise_connection(scope, params)
        "validate" -> Organizations.validate_enterprise_connection(scope, params)
        "activate" -> Organizations.activate_enterprise_connection(scope, params)
      end

    case result do
      {:ok, connection} ->
        {:noreply,
         socket
         |> assign(:enterprise_connection, connection)
         |> assign_enterprise_form()
         |> put_flash(:info, enterprise_flash(action))}

      {:error, :validation_failed} ->
        {:noreply,
         socket
         |> assign(:enterprise_connection, Organizations.get_enterprise_connection(scope))
         |> assign_enterprise_form()
         |> put_flash(
           :error,
           "Enterprise connection stayed non-active because validation failed."
         )}

      {:error, :validation_failed, connection} ->
        {:noreply,
         socket
         |> assign(:enterprise_connection, connection)
         |> assign_enterprise_form()
         |> put_flash(
           :error,
           "Enterprise connection stayed non-active because validation failed."
         )}

      {:error, %Ecto.Changeset{} = changeset} ->
        {:noreply,
         assign(
           socket,
           :enterprise_form,
           to_form(%{changeset | action: :validate}, as: :enterprise_connection)
         )}
    end
  end

  def handle_event("save_auth_policy", %{"auth_policy" => params, "_action" => action}, socket) do
    scope = socket.assigns.current_scope

    result =
      case action do
        "enable_sso_only" ->
          Organizations.enable_sso_only(scope, Map.get(params, "break_glass_user_ids", []))

        "disable_sso_only" ->
          Organizations.disable_sso_only(scope)
      end

    case result do
      {:ok, %{policy: policy, exemptions: exemptions}} ->
        {:noreply,
         socket
         |> assign(:auth_policy, policy)
         |> assign(:break_glass_exemptions, exemptions)
         |> assign(:auth_policy_form, blank_auth_policy_form())
         |> put_flash(:info, "SSO-only policy updated.")}

      {:ok, policy} ->
        {:noreply,
         socket
         |> assign(:auth_policy, policy)
         |> assign(:break_glass_exemptions, Organizations.list_auth_policy_exemptions(scope))
         |> assign(:auth_policy_form, blank_auth_policy_form())
         |> put_flash(:info, "SSO-only policy updated.")}

      {:error, :break_glass_required} ->
        {:noreply,
         socket
         |> assign(
           :auth_policy_form,
           auth_policy_form_with_error(
             params,
             "Select at least one break-glass member before enabling SSO-only."
           )
         )
         |> put_flash(:error, "SSO-only needs an explicit break-glass member.")}

      {:error, :invalid_break_glass_users} ->
        {:noreply,
         socket
         |> assign(
           :auth_policy_form,
           auth_policy_form_with_error(
             params,
             "Select only current organization members as break-glass users."
           )
         )
         |> put_flash(:error, "Break-glass users must belong to this organization.")}

      {:error, %Ecto.Changeset{} = changeset} ->
        {:noreply,
         assign(
           socket,
           :auth_policy_form,
           to_form(%{changeset | action: :validate}, as: :auth_policy)
         )}
    end
  end

  def handle_event("disable_enterprise_connection", _params, socket) do
    case Organizations.disable_enterprise_connection(socket.assigns.current_scope) do
      {:ok, connection} ->
        {:noreply,
         socket
         |> assign(:enterprise_connection, connection)
         |> assign_enterprise_form()
         |> put_flash(:info, "Enterprise connection disabled.")}

      {:error, :not_found} ->
        {:noreply, put_flash(socket, :error, "No enterprise connection is configured yet.")}
    end
  end

  # ──────────────────────────────────────────────────────────────────────────
  # Form builders + error remapping
  #
  # The library's update_slug/4 and soft_delete_organization/4 functions use
  # a virtual changeset ({%{}, types}) and surface raw validation messages
  # like "is reserved" / "has already been taken" / "does not match current
  # slug". This LV remaps those into the exact UI-SPEC copy shown to users
  # (UI-SPEC §Copywriting Contract Error States).
  # ──────────────────────────────────────────────────────────────────────────

  defp blank_slug_form do
    to_form(%{"slug" => "", "password" => "", "confirm_slug" => ""}, as: :slug_change)
  end

  defp blank_delete_form do
    to_form(%{"password" => "", "confirm_name" => ""}, as: :delete_org)
  end

  defp blank_auth_policy_form do
    to_form(%{"break_glass_user_ids" => []}, as: :auth_policy)
  end

  defp slug_form_with_errors(params, errors) do
    types = %{slug: :string, password: :string, confirm_slug: :string}

    changeset =
      {%{}, types}
      |> Ecto.Changeset.cast(normalize(params), Map.keys(types))

    changeset =
      Enum.reduce(errors, changeset, fn {field, msg}, acc ->
        Ecto.Changeset.add_error(acc, field, msg)
      end)

    to_form(%{changeset | action: :validate}, as: :slug_change)
  end

  defp delete_form_with_errors(params, errors) do
    types = %{password: :string, confirm_name: :string}

    changeset =
      {%{}, types}
      |> Ecto.Changeset.cast(normalize(params), Map.keys(types))

    changeset =
      Enum.reduce(errors, changeset, fn {field, msg}, acc ->
        Ecto.Changeset.add_error(acc, field, msg)
      end)

    to_form(%{changeset | action: :validate}, as: :delete_org)
  end

  defp normalize(params) when is_map(params), do: params
  defp normalize(_), do: %{}

  defp auth_policy_form_with_error(params, message) do
    changeset =
      {%{}, %{break_glass_user_ids: {:array, :string}}}
      |> Ecto.Changeset.cast(normalize(params), [:break_glass_user_ids])
      |> Ecto.Changeset.add_error(:break_glass_user_ids, message)

    to_form(%{changeset | action: :validate}, as: :auth_policy)
  end

  defp assign_enterprise_form(socket) do
    scope = socket.assigns.current_scope

    changeset =
      Organizations.change_enterprise_connection(
        scope,
        default_enterprise_attrs(socket.assigns[:enterprise_connection])
      )

    assign(socket, :enterprise_form, to_form(changeset, as: :enterprise_connection))
  end

  defp default_enterprise_attrs(nil) do
    %{
      "display_name" => "",
      "login_hint_domains" => "",
      "oidc_settings" => %{
        "issuer" => "",
        "discovery_document_uri" => "",
        "client_id" => "",
        "encrypted_client_secret" => "",
        "client_authentication_method" => "client_secret_basic",
        "scopes" => "openid, profile, email"
      }
    }
  end

  defp default_enterprise_attrs(_connection), do: %{}

  defp enterprise_status(nil), do: "draft"
  defp enterprise_status(connection), do: connection.status

  defp auth_policy_status(policy) do
    case policy.enforcement_mode do
      :sso_required -> "sso_required"
      _ -> "optional"
    end
  end

  defp enterprise_flash("save"), do: "Enterprise connection draft saved."
  defp enterprise_flash("validate"), do: "Enterprise connection validated."
  defp enterprise_flash("activate"), do: "Enterprise connection activated."

  defp csv_value(value) when is_list(value), do: Enum.join(value, ", ")
  defp csv_value(value) when is_binary(value), do: value
  defp csv_value(_value), do: ""

  defp candidate_selected?(exemptions, user_id) do
    Enum.any?(exemptions, &(&1.user_id == user_id))
  end

  # Remap library-emitted slug error messages to the exact UI-SPEC copy.
  #
  # Library messages we expect:
  #   :slug         → "is reserved" (validate_exclusion)
  #   :slug         → "has invalid format" (validate_format)
  #   :slug         → "has already been taken" (unique_constraint — if surfaced)
  #   :confirm_slug → "does not match current slug" (validate_confirm)
  #   :password     → "can't be blank" (validate_required)
  #   :slug         → "can't be blank" (validate_required)
  defp remap_slug_errors(%Ecto.Changeset{errors: errors}, current_slug) do
    Enum.map(errors, fn {field, {msg, _opts}} ->
      {field, remap_slug_error(field, msg, current_slug)}
    end)
  end

  defp remap_slug_error(:slug, "is reserved", _current_slug),
    do: "That slug is reserved. Try another."

  defp remap_slug_error(:slug, "has already been taken", _current_slug),
    do: "That slug is already in use. Try another."

  defp remap_slug_error(:slug, "has invalid format", _current_slug),
    do: "Slugs can only contain lowercase letters, numbers, and hyphens."

  defp remap_slug_error(:confirm_slug, "does not match current slug", current_slug),
    do: "Type " <> current_slug <> " exactly to confirm."

  defp remap_slug_error(_field, msg, _current_slug), do: msg

  defp remap_delete_errors(%Ecto.Changeset{errors: errors}, org_name) do
    Enum.map(errors, fn {field, {msg, _opts}} ->
      {field, remap_delete_error(field, msg, org_name)}
    end)
  end

  defp remap_delete_error(:confirm_name, "does not match organization name", org_name),
    do: "Type " <> org_name <> " exactly to confirm."

  defp remap_delete_error(_field, msg, _org_name), do: msg
end
