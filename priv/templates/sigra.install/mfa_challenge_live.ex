defmodule <%= web_module %>.MFAChallengeLive do
  @moduledoc """
  LiveView for the MFA challenge page.

  Provides two-factor authentication verification with TOTP
  authenticator code and backup code tabs, auto-submit on 6 digits,
  and trust-this-browser checkbox.

  Generated by `mix sigra.install --live`. Customize freely -- this module
  is owned by your application.
  """
  use <%= web_module %>, :live_view

  alias <%= context_module %>, as: Auth

  def mount(_params, session, socket) do
    mfa_pending = session["mfa_pending"]

    if mfa_pending != true do
      {:ok,
       socket
       |> put_flash(:error, "No MFA challenge pending.")
       |> redirect(to: ~p"/")}
    else
      user = socket.assigns.current_scope.user
      masked_email = mask_email(user.email)

      {:ok,
       assign(socket,
         active_tab: "totp",
         masked_email: masked_email,
         totp_form: to_form(%{"code" => "", "trust" => "false"}, as: "mfa"),
         backup_form: to_form(%{"code" => ""}, as: "mfa"),
         page_title: "Two-factor authentication"
       )}
    end
  end

  def render(assigns) do
    ~H"""
    <div class="mx-auto max-w-sm">
      <.header>
        Two-factor authentication
        <:subtitle>
          Enter the code for <%= "{@masked_email}" %>
        </:subtitle>
      </.header>

      <%% # Tab bar (D-21) %>
      <div class="mt-6" role="tablist" aria-label="Verification method">
        <div class="flex border-b border-gray-200">
          <button
            type="button"
            role="tab"
            id="tab-totp"
            aria-selected={to_string(@active_tab == "totp")}
            aria-controls="panel-totp"
            phx-click="switch_tab"
            phx-value-tab="totp"
            class={"px-4 py-2 text-sm font-semibold border-b-2 -mb-px #{if @active_tab == "totp", do: "border-brand text-brand", else: "border-transparent text-gray-500 hover:text-gray-700"}"}
          >
            Authenticator code
          </button>
          <button
            type="button"
            role="tab"
            id="tab-backup"
            aria-selected={to_string(@active_tab == "backup")}
            aria-controls="panel-backup"
            phx-click="switch_tab"
            phx-value-tab="backup"
            class={"px-4 py-2 text-sm font-semibold border-b-2 -mb-px #{if @active_tab == "backup", do: "border-brand text-brand", else: "border-transparent text-gray-500 hover:text-gray-700"}"}
          >
            Backup code
          </button>
        </div>
      </div>

      <%% # TOTP Tab Content %>
      <div
        :if={@active_tab == "totp"}
        id="panel-totp"
        role="tabpanel"
        aria-labelledby="tab-totp"
        class="mt-6"
      >
        <.form
          for={@totp_form}
          id="mfa_totp_form"
          phx-change="validate_totp"
          phx-submit="verify_totp"
        >
          <div class="space-y-4">
            <div>
              <label for="mfa_totp_code" class="block text-sm font-semibold leading-normal text-zinc-800">
                Authenticator code
              </label>
              <input
                type="text"
                id="mfa_totp_code"
                name="mfa[code]"
                value={@totp_form[:code].value}
                inputmode="numeric"
                pattern="[0-9]*"
                maxlength="6"
                autocomplete="one-time-code"
                autofocus
                required
                class="mt-2 block w-full rounded-lg text-base font-mono text-center tracking-widest text-zinc-900 focus:ring-0 sm:text-sm/6 phx-no-feedback:border-zinc-300 phx-no-feedback:focus:border-zinc-400 border-zinc-300 focus:border-zinc-400"
                aria-label="6-digit authenticator code"
              />
            </div>

            <label class="flex items-center gap-2 text-sm text-gray-600">
              <input
                type="checkbox"
                name="mfa[trust]"
                value="true"
                class="rounded border-gray-300"
              />
              Trust this browser for 30 days
            </label>

            <.button phx-disable-with="Verifying..." class="w-full">
              Verify
            </.button>
          </div>
        </.form>
      </div>

      <%% # Backup Code Tab Content %>
      <div
        :if={@active_tab == "backup"}
        id="panel-backup"
        role="tabpanel"
        aria-labelledby="tab-backup"
        class="mt-6"
      >
        <.form
          for={@backup_form}
          id="mfa_backup_form"
          phx-submit="verify_backup"
        >
          <div class="space-y-4">
            <div>
              <label for="mfa_backup_code" class="block text-sm font-semibold leading-normal text-zinc-800">
                Backup code
              </label>
              <input
                type="text"
                id="mfa_backup_code"
                name="mfa[code]"
                value={@backup_form[:code].value}
                placeholder="XXXX-XXXX"
                required
                class="mt-2 block w-full rounded-lg text-base font-mono text-zinc-900 focus:ring-0 sm:text-sm/6 phx-no-feedback:border-zinc-300 phx-no-feedback:focus:border-zinc-400 border-zinc-300 focus:border-zinc-400"
                aria-label="Backup code"
              />
            </div>

            <.button phx-disable-with="Verifying..." class="w-full">
              Verify
            </.button>
          </div>
        </.form>
      </div>

      <%% # Remaining attempts hint (D-38) %>
      <div class="mt-4 text-center" aria-live="polite">
        <p class="text-sm text-gray-500">
          Enter the code from your authenticator app to continue.
        </p>
      </div>

      <%% # Cancel link (D-34) %>
      <p class="mt-6 text-center text-sm">
        <.link href={~p"/users/log_out"} method="delete" class="text-gray-500 hover:underline">
          Cancel and sign out
        </.link>
      </p>
    </div>
    """
  end

  def handle_event("switch_tab", %{"tab" => tab}, socket) when tab in ["totp", "backup"] do
    {:noreply, assign(socket, active_tab: tab)}
  end

  def handle_event("validate_totp", %{"mfa" => %{"code" => code}}, socket) do
    form = to_form(%{"code" => code, "trust" => "false"}, as: "mfa")

    # Auto-submit when 6 digits entered (D-36)
    if String.length(code) == 6 and Regex.match?(~r/^\d{6}$/, code) do
      send(self(), {:auto_verify_totp, code})
    end

    {:noreply, assign(socket, totp_form: form)}
  end

  def handle_event("verify_totp", %{"mfa" => params}, socket) do
    user = socket.assigns.current_scope.user
    code = params["code"] || ""
    trust = params["trust"] == "true"

    case Auth.mfa_verify(user, code) do
      {:ok, _} ->
        {:noreply,
         socket
         |> put_flash(:info, "Two-factor authentication verified.")
         |> redirect(to: ~p"/")}

      {:error, :invalid_code, remaining} ->
        form = to_form(%{"code" => "", "trust" => to_string(trust)}, as: "mfa")

        {:noreply,
         socket
         |> put_flash(:error, "Invalid verification code. #{remaining} attempts remaining.")
         |> assign(totp_form: form)}

      {:error, :lockout, seconds} ->
        minutes = div(seconds + 59, 60)

        {:noreply,
         socket
         |> put_flash(:error, "Too many failed attempts. Try again in #{minutes} minutes.")}

      {:error, :not_enrolled} ->
        {:noreply,
         socket
         |> put_flash(:error, "MFA is not enabled on your account.")
         |> redirect(to: ~p"/users/settings")}
    end
  end

  def handle_event("verify_backup", %{"mfa" => params}, socket) do
    user = socket.assigns.current_scope.user
    code = params["code"] || ""

    case Auth.mfa_verify_backup(user, code) do
      {:ok, _, _remaining} ->
        {:noreply,
         socket
         |> put_flash(:info, "Two-factor authentication verified.")
         |> redirect(to: ~p"/")}

      {:error, :invalid_backup_code, remaining} ->
        form = to_form(%{"code" => ""}, as: "mfa")

        {:noreply,
         socket
         |> put_flash(:error, "Invalid verification code. #{remaining} attempts remaining.")
         |> assign(backup_form: form)}

      {:error, :lockout, seconds} ->
        minutes = div(seconds + 59, 60)

        {:noreply,
         socket
         |> put_flash(:error, "Too many failed attempts. Try again in #{minutes} minutes.")}

      {:error, :not_enrolled} ->
        {:noreply,
         socket
         |> put_flash(:error, "MFA is not enabled on your account.")
         |> redirect(to: ~p"/users/settings")}
    end
  end

  def handle_info({:auto_verify_totp, code}, socket) do
    handle_event("verify_totp", %{"mfa" => %{"code" => code, "trust" => "false"}}, socket)
  end

  defp mask_email(email) do
    case String.split(email, "@") do
      [local, domain] ->
        first = String.first(local)
        "#{first}***@#{domain}"

      _ ->
        "***"
    end
  end
end
