  def handle_event("validate_totp", %{"mfa" => %{"code" => code}}, socket) do
    form = to_form(%{"code" => code, "trust" => "false"}, as: "mfa")

    # Auto-submit when 6 digits entered (D-36)
    if String.length(code) == 6 and Regex.match?(~r/^\d{6}$/, code) do
      send(self(), {:auto_verify_totp, code})
    end

    {:noreply, assign(socket, totp_form: form)}
  end

  def handle_event("verify_totp", %{"mfa" => params}, socket) do
    user = socket.assigns.current_scope.user
    code = params["code"] || ""
    trust = params["trust"] == "true"

    case Auth.mfa_verify(user, code) do
      {:ok, _} ->
        {:noreply,
         socket
         |> put_flash(:info, "Two-factor authentication verified.")
         |> redirect(to: ~p"/")}

      {:error, :invalid_code, remaining} ->
        form = to_form(%{"code" => "", "trust" => to_string(trust)}, as: "mfa")

        {:noreply,
         socket
         |> put_flash(:error, "Invalid verification code. #{remaining} attempts remaining.")
         |> assign(totp_form: form)}

      {:error, :lockout, seconds} ->
        minutes = div(seconds + 59, 60)

        {:noreply,
         socket
         |> put_flash(:error, "Too many failed attempts. Try again in #{minutes} minutes.")}

      {:error, :not_enrolled} ->
        {:noreply,
         socket
         |> put_flash(:error, "MFA is not enabled on your account.")
         |> redirect(to: ~p"/users/settings")}
    end
  end

  def handle_event("verify_backup", %{"mfa" => params}, socket) do
    user = socket.assigns.current_scope.user
    code = params["code"] || ""

    case Auth.mfa_verify_backup(user, code) do
      {:ok, _, _remaining} ->
        {:noreply,
         socket
         |> put_flash(:info, "Two-factor authentication verified.")
         |> redirect(to: ~p"/")}

      {:error, :invalid_backup_code, remaining} ->
        form = to_form(%{"code" => ""}, as: "mfa")

        {:noreply,
         socket
         |> put_flash(:error, "Invalid verification code. #{remaining} attempts remaining.")
         |> assign(backup_form: form)}

      {:error, :lockout, seconds} ->
        minutes = div(seconds + 59, 60)

        {:noreply,
         socket
         |> put_flash(:error, "Too many failed attempts. Try again in #{minutes} minutes.")}

      {:error, :not_enrolled} ->
        {:noreply,
         socket
         |> put_flash(:error, "MFA is not enabled on your account.")
         |> redirect(to: ~p"/users/settings")}
    end
  end

  def handle_info({:auto_verify_totp, code}, socket) do
    handle_event("verify_totp", %{"mfa" => %{"code" => code, "trust" => "false"}}, socket)
  end

  defp mask_email(email) do
    case String.split(email, "@") do
      [local, domain] ->
        first = String.first(local)
        "#{first}***@#{domain}"

      _ ->
        "***"
    end
  end

<%= if passkeys? do %>
  defp passkey_recovery_bucket(payload) when is_map(payload) do
    payload
    |> Map.take(["name", "code", "message"])
    |> Map.values()
    |> Enum.join(" ")
    |> String.downcase()
    |> then(fn value ->
      cond do
        String.contains?(value, "timeout") ->
          :timeout

        String.contains?(value, "unsupported") or String.contains?(value, "not_supported") ->
          :unsupported

        true ->
          :generic
      end
    end)
  end

  defp passkey_recovery_bucket(_payload), do: :generic

  defp passkey_recovery_notice(:canceled) do
    %{
      tone: :neutral,
      title: "Nothing changed.",
      body: "Try again or use another way."
    }
  end

  defp passkey_recovery_notice(:timeout) do
    %{
      tone: :warning,
      title: "We couldn't finish passkey sign-in. Try again or use another way to continue.",
      body: nil
    }
  end

  defp passkey_recovery_notice(:unsupported) do
    %{
      tone: :info,
      title: "Passkeys aren't available in this browser.",
      body: "Use your authenticator code, a backup code, or a device/browser that supports passkeys."
    }
  end

  defp passkey_recovery_notice(:generic) do
    %{
      tone: :warning,
      title: "We couldn't finish passkey sign-in. Try again or use another way to continue.",
      body: nil
    }
  end

  defp passkey_notice_class(:warning), do: "sigra-auth-notice--warning"
  defp passkey_notice_class(:info), do: ""
  defp passkey_notice_class(:neutral), do: ""
<% end %>
