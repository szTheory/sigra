defmodule <%= context_module %>.UserAPIToken do
  @moduledoc """
  Ecto schema for user API tokens (personal access tokens).

  Each token provides programmatic API access with scoped permissions
  and optional expiration. Tokens are stored as SHA-256 hashes; the
  raw key is shown only once at creation time.

  Maps to the `Sigra.APIToken` library module for all security-critical
  operations (creation, verification, revocation).

  Generated by `mix sigra.install --api`. Customize freely -- this
  module is owned by your application.
  """

  use Ecto.Schema

  @primary_key {:id, :binary_id, autogenerate: true}
  @foreign_key_type :binary_id

  schema "user_api_tokens" do
    field :hashed_token, :binary
    field :prefix, :string
    field :name, :string
    field :scopes, {:array, :string}, default: []
    field :last_used_at, :utc_datetime_usec
    field :expires_at, :utc_datetime
    field :revoked_at, :utc_datetime
    field :inserted_at, :utc_datetime_usec

    belongs_to :user, <%= context_module %>.<%= schema_alias %>
  end
end
