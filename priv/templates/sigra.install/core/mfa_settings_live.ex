  defp classify_passkey_error(text) do
    cond do
      String.contains?(text, "timeout") ->
        :timeout

      String.contains?(text, "unsupported") or String.contains?(text, "not_supported") or
          String.contains?(text, "notallowed") ->
        :unsupported

      true ->
        :generic
    end
  end

