        nil -> ""
        passkey -> passkey.nickname || ""
      end

    {:noreply,
     assign(socket,
       renaming_passkey_id: credential_id,
       rename_form: to_form(%{"nickname" => nickname}, as: "passkey"),
       deleting_passkey_id: nil
     )}
  end

