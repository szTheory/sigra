  # -- Event Handlers --

  def handle_event("begin_enrollment", _params, socket) do
    user = socket.assigns.current_scope.user

    case Auth.mfa_enroll(account: user.email) do
      {:ok, enrollment} ->
        {:noreply,
         assign(socket,
           enrollment_step: :qr,
           svg: enrollment.svg,
           base32_secret: enrollment.secret,
           raw_secret: enrollment.raw_secret
         )}
    end
  end

  def handle_event("validate_enroll", %{"enroll" => %{"code" => code}}, socket) do
    form = to_form(%{"code" => code}, as: "enroll")
    socket = assign(socket, enroll_form: form)

    # Auto-submit when 6 digits entered (D-36). 10.1 IN-06 follow-up:
    # call the confirm path directly instead of dispatching via
    # `send(self(), …)`. The mailbox round-trip allowed a stale 6-digit
    # prefix to fire after the user typed a 7th character, wasting an
    # attempt against the MFA lockout counter.
    if String.length(code) == 6 and Regex.match?(~r/^\d{6}$/, code) do
      do_confirm_enrollment(socket, code)
    else
      {:noreply, socket}
    end
  end

  def handle_event("confirm_enrollment", %{"enroll" => %{"code" => code}}, socket) do
    do_confirm_enrollment(socket, code)
  end

  def handle_event("toggle_acknowledge", _params, socket) do
    {:noreply, assign(socket, codes_acknowledged: !socket.assigns.codes_acknowledged)}
  end

  def handle_event("complete_enrollment", _params, socket) do
    if socket.assigns.codes_acknowledged do
      user = socket.assigns.current_scope.user
      mfa_status = Auth.mfa_status(user)

      {:noreply,
       assign(socket,
         mfa_enabled: true,
         enrollment_step: nil,
         backup_codes: [],
         backup_remaining: mfa_status.backup_codes_remaining,
         codes_acknowledged: false
       )}
    else
      {:noreply, socket}
    end
  end

  defp do_confirm_enrollment(socket, code) do
    user = socket.assigns.current_scope.user
    raw_secret = socket.assigns.raw_secret

    case Auth.mfa_confirm_enrollment(user, raw_secret, code) do
      {:ok, %{backup_codes: codes}} ->
        {:noreply,
         socket
         |> put_flash(:info, "Two-factor authentication has been enabled.")
         |> assign(
           enrollment_step: :backup_codes,
           backup_codes: codes,
           codes_acknowledged: false,
           raw_secret: nil
         )}

      {:error, :invalid_code} ->
        form = to_form(%{"code" => ""}, as: "enroll")

        {:noreply,
         socket
         |> put_flash(:error, "Invalid verification code. Please try again.")
         |> assign(enroll_form: form)}
    end
  end

